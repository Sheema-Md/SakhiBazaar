<section>
    <h2>Types of Small Business Loans</h2>
    <ul>
        <li><strong>Term Loans:</strong> Fixed amount of capital repaid over time with interest.</li>
        <li><strong>SBA Loans:</strong> Loans partially guaranteed by the U.S. Small Business Administration.</li>
        <li><strong>Microloans:</strong> Small loans (typically under $50,000) for startups and small businesses.</li>
        <li><strong>Business Lines of Credit:</strong> Flexible loan option that allows you to draw funds as needed.</li>
        <li><strong>Equipment Financing:</strong> Loans used specifically to purchase equipment.</li>
        <li><strong>Invoice Financing:</strong> Borrowing against unpaid customer invoices.</li>
    </ul>
</section>

<section>
